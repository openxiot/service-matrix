package cc.openxiot.matrix.db.dashboard.web.widget;

import java.util.Map;

/**
 * 卡片的尺寸档位（用户说的「几个固定的尺寸」）：每档对应一个占几列几行的格子（24 列网格）。
 *
 * <p><b>档位名说的就是这一档的两件事</b>：{@code W} 后面是占几列，{@code H} 后面是像素高
 * —— {@code W6H200} 读作「6 列宽、200 像素高」。名字里放<b>像素</b>而不是行数，是因为行高
 * 在历史上改过一次（38 → 92，每一档的行数都跟着减半），而像素高从头到尾没变：
 * 名字里写行数的话，那一次改动就得迁移库里每一个文档，写像素则不用。</p>
 *
 * <p><b>服务端只认档位名，不持有占格知识</b>：这一侧能回答的只有「这个档位名认不认识」，
 * 至于每一档占几列几行、像素高度怎么算，全在<b>前端</b>的 {@code WIDGET_SIZES}
 * （{@code typedef/define/dashboard/DashboardLayout.ts}）与 {@code dashboard.grid} 里。
 * 加一档时这里加一个枚举常量、前端加一行表，<b>两边一起改</b> —— 数值不必同步，
 * 因为服务端根本不用它。（{@link #of(String)} 那张旧名表是唯一的例外，
 * 它只做新旧名字的翻译，同样不碰占格。）</p>
 *
 * <p>为什么要这么切：排版是渲染方的知识。服务端既不知道容器宽多少，也无法验证
 * 「4 张 {@code W6H200} 正好一行」，硬留一份 w/h 只会多出一份会过期的真值（本轮改造之前就是那样：
 * 卡片上有 {@code layout.w/h} 两个字段，还要靠 {@code applyTo} 按档位覆盖一次，
 * 再在别处校验 {@code x + w ≤ 24}）。<b>改造时把坐标请回卡片上，只请回了
 * {@code x}/{@code y} 两个数，{@code w}/{@code h} 一个字节都没上行</b> ——
 * 用户摆的是位置，占格仍然只有前端知道。所以那句 {@code x + w ≤ 24} 在这里
 * 仍然无从校验，档位表也仍然只有一份。</p>
 *
 * <p>现有十档（像素高由前端的 {@code h × 92 + (h − 1) × 16} 算出来，
 * 宽度按内容区 1400px、列宽 ≈ 43px 估算）：
 * {@code W6H92} ≈ 338×92、{@code W12H92} ≈ 692×92（这两个<b>统计卡专用</b>，那种卡没有卡头、
 * 按内容自然高约 90px）、{@code W6H200} ≈ 338×200、{@code W12H200} ≈ 692×200、
 * {@code W24H200} = 1400×200（整宽的横幅）、{@code W6H308} ≈ 338×308、
 * {@code W12H308} ≈ 692×308、{@code W24H308} = 1400×308、
 * {@code W12H416} ≈ 692×416、{@code W24H416} = 1400×416。</p>
 *
 * <p>几张卡片同宽、只有高度不同（如 {@code W12H200} 与 {@code W12H416}）是故意的：
 * 「宽图」和「高图」是两种不同的需求，用同一宽度区分高度比引入更多宽度更好记。
 * 也有<b>故意不存在的组合</b>：6 宽没有 416（那样的图太窄太高，不成形状，而竖着叠两张矮卡
 * 就能拼出同样的高度），24 宽没有 92 那一档（整宽的一行高更像一条分隔线，不是一张卡）。</p>
 */
public enum WidgetSize {

    /** 一行高的窄档：**统计卡专用**（那种卡没有卡头，按内容自然高约 90px） */
    W6H92,
    /** 一行高的半宽档：**统计卡专用** */
    W12H92,
    /** 窄的半高卡：单值、小型数字 */
    W6H200,
    /** 半宽的标准档：单曲线、分布图 */
    W12H200,
    /** 整宽的矮档：横向的横幅（一排读数、一行状态） */
    W24H200,
    /** 窄的三行档：正好是「三张统计卡竖着叠起来」那一条（92 + 16 + 92 + 16 + 92） */
    W6H308,
    /** 半宽的三行档：比标准档多一行的曲线 */
    W12H308,
    /** 整宽的三行档 */
    W24H308,
    /** 半宽的高档：双高曲线 */
    W12H416,
    /** 整宽的大图 */
    W24H416;

    /**
     * 改造前的档位名 → 现在的名字。**只做名字翻译，不改尺寸**：每一组的前后两档占格完全相同
     * （{@code S} 与 {@code W6H200} 都是 6 列 2 行），所以翻译过去用户看不出任何变化。
     *
     * <p>留着它是因为<b>请求可能来自一个还没刷新的前端</b>：用户开着一个旧标签页、
     * 或者浏览器缓存着上一版脚本，保存时发过来的仍是旧名。不认的话整个 PUT 被拒
     * （400，文案说尺寸不认识），用户那一屏的改动就白做了，而他唯一的线索是一句看不懂的报错。
     * 认下来则是一次无声的、几何上等价的翻译 —— 下一次保存库里就落成新名了，不需要迁移脚本。</p>
     *
     * <p>前端读线格式时有一张同样作用的旧名表（{@code DashboardLayoutCodec} 的
     * {@code LEGACY_SIZES}）：那边管「存量的文档读出来是什么」，这边管「旧客户端写进来的是什么」，
     * 两边都要有，谁也替不了谁。</p>
     */
    private static final Map<String, WidgetSize> LEGACY_NAMES = Map.of(
            "S1", W6H92,
            "M1", W12H92,
            "S", W6H200,
            "M", W12H200,
            "L", W12H416,
            "XL", W24H416);

    /**
     * 按档位名解析：**现名 → 旧名（见 {@link #LEGACY_NAMES}）→ 不认识**。
     * 不认识（含 null、大小写不符、将来某个版本才有的档位）返回 {@code null}，
     * 由调用方给出错误文案。
     */
    public static WidgetSize of(String size) {
        if (size == null) {
            return null;
        }
        for (WidgetSize value : values()) {
            if (value.name().equals(size)) {
                return value;
            }
        }
        return LEGACY_NAMES.get(size);
    }
}
